const CAPTION_CLASS = "text-[10px] uppercase tracking-wider text-[var(--color-text-faint)]";

/**
 * Worked CSV example: a real table for reading, plus the raw line for pasting.
 * Mirrors the in-app «Формат CSV — колонки и пример» block (CsvFormatHelp.tsx), and both
 * are kept in step with the examples in src/components/csvFormats.ts.
 */
function CsvSample({
  caption,
  header,
  rows,
  raw,
}: {
  caption: string;
  header: string[];
  rows: string[][];
  raw: string;
}) {
  return (
    <figure className="my-4 space-y-2">
      <figcaption className={CAPTION_CLASS}>{caption}</figcaption>
      <div className="overflow-x-auto rounded-md border border-[var(--color-border)] bg-[var(--color-surface)]">
        <table className="w-full text-[11px] border-collapse">
          <thead>
            <tr className="bg-[var(--color-surface-2)]">
              {header.map((h) => (
                <th
                  key={h}
                  className="text-left font-medium px-2 py-1.5 whitespace-nowrap border-b border-[var(--color-border)] text-[var(--color-text)]"
                >
                  {h}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((row, ri) => (
              <tr key={ri} className={ri > 0 ? "border-t border-[var(--color-border)]" : ""}>
                {header.map((h, ci) => (
                  <td key={h} className="px-2 py-1.5 font-mono whitespace-nowrap text-[var(--color-text-dim)]">
                    {row[ci] ?? ""}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <div className={CAPTION_CLASS}>То же самое CSV-текстом — это и вставляйте в поле</div>
      <pre className="overflow-x-auto rounded-md border border-[var(--color-border)] bg-[var(--color-surface)] p-3 text-[11px] leading-relaxed font-mono text-[var(--color-text)] whitespace-pre">
        {raw}
      </pre>
    </figure>
  );
}

interface ColumnSpec {
  name: string;
  /** Shorthand for the two common cases; ignored when `need` is given. */
  required?: boolean;
  /** Free-text override for columns whose obligation depends on the mode. */
  need?: string;
  desc: string;
  aliases?: string;
}

/** Column reference: name / obligation / meaning (+ accepted header synonyms). */
function ColumnsTable({ rows, aliasHeader }: { rows: ColumnSpec[]; aliasHeader?: string }) {
  return (
    <div className="overflow-x-auto my-3">
      <table className="w-full text-xs border-collapse">
        <thead>
          <tr className={`text-left ${CAPTION_CLASS}`}>
            <th className="font-medium py-1 pr-3 whitespace-nowrap">Колонка</th>
            <th className="font-medium py-1 pr-3 whitespace-nowrap">Нужна?</th>
            <th className="font-medium py-1 pr-3">Что задаёт</th>
            {aliasHeader && <th className="font-medium py-1">{aliasHeader}</th>}
          </tr>
        </thead>
        <tbody>
          {rows.map((c) => (
            <tr key={c.name} className="border-t border-[var(--color-border)] align-top">
              <td className="py-1.5 pr-3 font-mono text-[var(--color-text)] whitespace-nowrap">{c.name}</td>
              <td
                className={`py-1.5 pr-3 ${
                  c.need || c.required ? "text-[var(--color-text)]" : "text-[var(--color-text-faint)]"
                }`}
              >
                {c.need ?? (c.required ? "обязательно" : "необязательно")}
              </td>
              <td className="py-1.5 pr-3 text-[var(--color-text-dim)]">{c.desc}</td>
              {aliasHeader && (
                <td className="py-1.5 font-mono text-[11px] text-[var(--color-text-dim)]">{c.aliases ?? ""}</td>
              )}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

