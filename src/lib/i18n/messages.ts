const messages: Record<Locale, typeof en> = { en, ru };

export type Messages = typeof en;
export type LeafKey<T, P extends string = ""> = {
  [K in keyof T]: T[K] extends string
    ? `${P}${P extends "" ? "" : "."}${K & string}`
    : T[K] extends Record<string, unknown>
      ? LeafKey<T[K], `${P}${P extends "" ? "" : "."}${K & string}`>
      : never;
}[keyof T];

export type MessageKey = LeafKey<Messages>;

export function getMessages(locale: Locale): Messages {
  return messages[locale] ?? messages.en;
}

export function translate(msgs: Messages, key: string, vars?: Record<string, string | number>): string {
  const parts = key.split(".");
  let cursor: unknown = msgs;
  for (const p of parts) {
    if (cursor && typeof cursor === "object" && p in (cursor as Record<string, unknown>)) {
      cursor = (cursor as Record<string, unknown>)[p];
    } else {
      return key; // fallback
    }
  }
  if (typeof cursor !== "string") return key;
  if (!vars) return cursor;
  return cursor.replace(/\{(\w+)\}/g, (_, n) => (vars[n] !== undefined ? String(vars[n]) : `{${n}}`));
}
